-- BellaMassa: esquema simples para Supabase/PostgreSQL.
--
-- ATENCAO: ESTE SCRIPT E DESTRUTIVO. Ele apaga as tabelas conhecidas da
-- BellaMassa e seus dados antes de recriar o esquema. Execute somente depois
-- de confirmar que nao ha dados dessas tabelas que queira preservar.
-- As contas e senhas em auth.users NAO sao apagadas.
--
-- Crie usuarios da equipe em Supabase > Authentication > Users. Depois,
-- conceda acesso criando um registro em public.perfis (exemplo no README).
-- Senhas nunca devem ser gravadas em tabelas publicas; Supabase Auth as gere.

-- Remova o trigger antigo de cadastro, se existir. Ele pertence a auth.users,
-- portanto nao e removido ao apagar as tabelas de public.
