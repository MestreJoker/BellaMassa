-- Confere se a sessao autenticada tem perfil de equipe.
CREATE OR REPLACE FUNCTION public.usuario_equipe()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.perfis p
        WHERE p.auth_user_id = (SELECT auth.uid())
    );
$$;

CREATE OR REPLACE FUNCTION public.usuario_admin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.perfis p
        WHERE p.auth_user_id = (SELECT auth.uid())
          AND p.is_admin
    );
$$;

REVOKE ALL ON FUNCTION public.usuario_equipe() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.usuario_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.usuario_equipe() TO authenticated;
GRANT EXECUTE ON FUNCTION public.usuario_admin() TO authenticated;

