-- Perfil de acesso: somente quem tiver registro aqui e usuario da equipe.
CREATE TABLE public.perfis (
    auth_user_id UUID PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    nome TEXT NOT NULL CHECK (length(btrim(nome)) > 0),
    email TEXT NOT NULL UNIQUE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Categorias e produtos com preco diretamente no produto.
CREATE TABLE public.categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE CHECK (length(btrim(nome)) > 0),
    ordem SMALLINT NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE public.produtos (
    id_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria BIGINT NOT NULL REFERENCES public.categorias (id_categoria) ON DELETE RESTRICT,
    nome TEXT NOT NULL CHECK (length(btrim(nome)) > 0),
    descricao TEXT NOT NULL DEFAULT '',
    tipo TEXT NOT NULL DEFAULT 'outro'
        CHECK (tipo IN ('pizza', 'bebida', 'sobremesa', 'borda', 'adicional', 'outro')),
    preco NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    imagem_url TEXT NOT NULL DEFAULT '',
    destaque BOOLEAN NOT NULL DEFAULT FALSE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (id_categoria, nome)
);

-- Clientes sao cadastrados manualmente pela equipe; endereco e mantido no proprio registro.
CREATE TABLE public.clientes (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL CHECK (length(btrim(nome)) > 0),
    telefone TEXT NOT NULL CHECK (length(btrim(telefone)) > 0),
    email TEXT,
    endereco TEXT NOT NULL DEFAULT '',
    bairro TEXT NOT NULL DEFAULT '',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Pedido guarda dados operacionais e um retrato do endereco usado na entrega.
CREATE TABLE public.pedidos (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES public.clientes (id_cliente) ON DELETE RESTRICT,
    data_pedido TIMESTAMPTZ NOT NULL DEFAULT now(),
    tipo_entrega TEXT NOT NULL CHECK (tipo_entrega IN ('entrega', 'retirada', 'balcao')),
    endereco_entrega TEXT NOT NULL DEFAULT '',
    forma_pagamento TEXT NOT NULL
        CHECK (forma_pagamento IN ('pix', 'cartao_credito', 'cartao_debito', 'dinheiro', 'outro')),
    status TEXT NOT NULL DEFAULT 'em_andamento'
        CHECK (status IN ('em_andamento', 'em_preparo', 'pronto', 'em_entrega', 'entregue', 'retirado', 'cancelado')),
    status_pagamento TEXT NOT NULL DEFAULT 'pendente'
        CHECK (status_pagamento IN ('pendente', 'pago')),
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    taxa_entrega NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (taxa_entrega >= 0),
    total NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    observacoes TEXT
);

-- Nome e preco ficam como snapshot para preservar o historico do pedido.
CREATE TABLE public.pedido_itens (
    id_item_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES public.pedidos (id_pedido) ON DELETE CASCADE,
    id_produto BIGINT REFERENCES public.produtos (id_produto) ON DELETE SET NULL,
    nome_produto TEXT NOT NULL,
    detalhes TEXT NOT NULL DEFAULT '',
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10, 2) NOT NULL CHECK (preco_unitario >= 0),
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0)
);

CREATE INDEX idx_produtos_categoria ON public.produtos (id_categoria);
