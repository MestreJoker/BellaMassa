-- Criacao atomica do pedido. Precos e nomes sao lidos do catalogo no banco.
CREATE OR REPLACE FUNCTION public.criar_pedido(
    p_cliente BIGINT,
    p_tipo_entrega TEXT,
    p_forma_pagamento TEXT,
    p_itens JSONB,
    p_observacoes TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_id_pedido BIGINT;
    v_item JSONB;
    v_id_produto BIGINT;
    v_quantidade INTEGER;
    v_nome TEXT;
    v_preco NUMERIC(10, 2);
    v_total_item NUMERIC(10, 2);
    v_subtotal NUMERIC(10, 2) := 0;
    v_taxa_entrega NUMERIC(10, 2) := 0;
    v_endereco TEXT := '';
BEGIN
    IF NOT public.usuario_equipe() THEN
        RAISE EXCEPTION 'Apenas usuarios da equipe podem criar pedidos.'
            USING ERRCODE = '42501';
    END IF;

    IF p_tipo_entrega NOT IN ('entrega', 'retirada', 'balcao')
       OR p_forma_pagamento NOT IN ('pix', 'cartao_credito', 'cartao_debito', 'dinheiro', 'outro') THEN
        RAISE EXCEPTION 'Tipo de entrega ou forma de pagamento invalido.';
    END IF;
    IF p_itens IS NULL OR jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens) = 0 THEN
        RAISE EXCEPTION 'O pedido precisa ter pelo menos um item.';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.clientes c
        WHERE c.id_cliente = p_cliente AND c.ativo
    ) THEN
        RAISE EXCEPTION 'Cliente inexistente ou inativo.';
    END IF;

    IF p_tipo_entrega = 'entrega' THEN
        SELECT concat_ws(' - ', NULLIF(btrim(c.endereco), ''), NULLIF(btrim(c.bairro), ''))
        INTO v_endereco
        FROM public.clientes c
        WHERE c.id_cliente = p_cliente;
        IF NULLIF(v_endereco, '') IS NULL THEN
            RAISE EXCEPTION 'O cliente precisa ter endereco cadastrado para entrega.';
        END IF;
        v_taxa_entrega := 7;
    END IF;

    INSERT INTO public.pedidos (
        id_cliente, tipo_entrega, endereco_entrega, forma_pagamento,
        status, status_pagamento, taxa_entrega, observacoes
    )
    VALUES (
        p_cliente, p_tipo_entrega, v_endereco, p_forma_pagamento,
        'em_andamento', 'pendente', v_taxa_entrega, NULLIF(btrim(p_observacoes), '')
    )
    RETURNING id_pedido INTO v_id_pedido;

    FOR v_item IN SELECT value FROM jsonb_array_elements(p_itens)
    LOOP
        v_id_produto := NULLIF(v_item ->> 'id_produto', '')::BIGINT;
        v_quantidade := COALESCE(NULLIF(v_item ->> 'quantidade', '')::INTEGER, 1);
        IF v_id_produto IS NULL OR v_quantidade <= 0 THEN
            RAISE EXCEPTION 'Produto ou quantidade do item invalido.';
        END IF;

        SELECT p.nome, p.preco
        INTO v_nome, v_preco
        FROM public.produtos p
        WHERE p.id_produto = v_id_produto AND p.ativo;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produto inexistente ou inativo.';
        END IF;

        v_total_item := v_preco * v_quantidade;
        INSERT INTO public.pedido_itens (
            id_pedido, id_produto, nome_produto, detalhes, quantidade, preco_unitario, total
        )
        VALUES (
            v_id_pedido, v_id_produto, v_nome,
            COALESCE(NULLIF(btrim(v_item ->> 'detalhes'), ''), ''),
            v_quantidade, v_preco, v_total_item
        );
        v_subtotal := v_subtotal + v_total_item;
    END LOOP;

    UPDATE public.pedidos
    SET subtotal = v_subtotal, total = v_subtotal + v_taxa_entrega
    WHERE id_pedido = v_id_pedido;

    RETURN v_id_pedido;
END;
$$;

CREATE OR REPLACE FUNCTION public.marcar_pedido_pago(p_id_pedido BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NOT public.usuario_equipe() THEN
        RAISE EXCEPTION 'Apenas usuarios da equipe podem atualizar pagamentos.'
            USING ERRCODE = '42501';
    END IF;

    UPDATE public.pedidos
    SET status_pagamento = 'pago'
    WHERE id_pedido = p_id_pedido
      AND status <> 'cancelado';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pedido nao encontrado.';
    END IF;
END;
$$;

